    // Signals for reactive state management
    workContractsSignal = signal<WorkContract[]>(this.workContracts);
    activeContractsSignal = signal<WorkContract[]>(this.workContracts.filter((contract) => contract.Status === 'Active'));

    constructor() {
        // Effects to observe changes and notify observers
        effect(() => {
            const contracts = this.workContractsSignal();
            this.workContractSubject.next(contracts);
        });

        effect(() => {
            const activeContracts = this.activeContractsSignal();
            this.activeContractsSubject.next(activeContracts);
        });
    }

    // Methods to get the work contracts
    getWorkContracts() {
        return this.workContractsSignal();
    }

    getActiveContracts() {
        return this.activeContractsSignal();
    }

    // Method to get a work contract by its unique ID (WorkContractName)
    getWorkContractById(id: string): WorkContract | undefined {
        return this.workContractsSignal().find((contract) => contract, 'Work Contract Name' === id);
    }

    // Computed values for filtered or derived data
    activeContractCount = computed(() => this.activeContractsSignal().length);
    allContractCount = computed(() => this.workContractsSignal().length);
